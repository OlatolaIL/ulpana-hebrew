const replacements = [
  // Bug fix: הרגל
  ['"hebrewPlain": "הרגיל"', '"hebrewPlain": "הרגל"'],

  // Compound & Prefixed phrases first
  ['מֵהַדֹּאַר', 'מֵהַדּוֹאַר'],
  ['הַדֹּאַר', 'הַדּוֹאַר'],
  ['דֹּאַר', 'דּוֹאַר'],
  ['בַּחֹרֶף', 'בַּחוֹרֶף'],
  ['חֹרֶף', 'חוֹרֶף'],
  ['הַמִּכְנָסַיִם', 'הַמִּכְנָסַיִּים'],
  ['מִכְנָסַיִם', 'מִכְנָסַיִּים'],
  ['מֶזֶג אֲוִיר', 'מֶזֶג אֲוִויר'],
  ['יוֹם הֻלֶּדֶת', 'יוֹם הוּלֶּדֶת'],
  ['קֻפַּת חוֹלִים', 'קוּפַּת חוֹלִים'],
  ['הַמְּסִבָּה', 'הַמְּסִיבָּה'],
  ['מְסִבַּת', 'מְסִיבַּת'],
  ['מְסִבָּה', 'מְסִיבָּה'],
  ['בְּתֵאָבוֹן', 'בְּתֵיאָבוֹן'],
  ['חֻלְצוֹת', 'חוּלְצוֹת'],
  ['חֻלְצָה', 'חוּלְצָה'],
  ['נַעֲלַיִם', 'נַעֲלַיִּים'],
  ['אָדֹם', 'אָדוֹם'],
  ['כָּחֹל', 'כָּחוֹל'],
  ['שָׁחֹר', 'שָׁחוֹר'],
  ['מִדּוֹת', 'מִידּוֹת'],
  ['מִדָּה', 'מִידָּה'],
  ['חֹם', 'חוֹם'],
  ['מְאֻחָר', 'מְאוּחָר'],
  ['מַשְׂכֹּרֶת', 'מַשְׂכּוֹרֶת'],
  ['נִסָּיוֹן', 'נִיסָּיוֹן'],
  ['שְׂחִיָּה', 'שְׂחִיָּיה'],
  ['בְּרֵכָה', 'בְּרֵיכָה'],
  ['מְזֻמָּן', 'מְזוּמָּן'],
  ['סִפּוּר', 'סִיפּוּר'],
  ['חֲתֻנָּה', 'חֲתוּנָּה'],
  ['חֲנֻכָּה', 'חֲנוּכָּה'],
  ['קִדּוּשׁ', 'קִידּוּשׁ'],
  ['סְתָו', 'סְתָיו'],

  // Pronoun forms of אית-
  ['אִתִּי', 'אִיתִּי'],
  ['אִתְּךָ', 'אִיתְּךָ'],
  ['אִתָּךְ', 'אִיתָּךְ'],
  ['אִתּוֹ', 'אִיתּוֹ'],
  ['אִתָּהּ', 'אִיתָּהּ'],
  ['אִתָּנוּ', 'אִיתָּנוּ'],
];

let totalReplaced = 0;
for (const [from, to] of replacements) {
  const matches = (content.match(new RegExp(from, 'g')) || []).length;
  if (matches > 0) {
    content = content.replaceAll(from, to);
    totalReplaced += matches;
    console.log(`Replaced "${from}" -> "${to}" (${matches} times)`);
  }
}

fs.writeFileSync(filePath, content, 'utf8');
console.log(`\nDone! Total replacements in ${filePath}: ${totalReplaced}`);
