import fs from 'fs';

const filePath = 'src/data/lessons/alef_36_50.ts';
let content = fs.readFileSync(filePath, 'utf8');

const replacements = [
  // Compound / prefixed phrases first
  ['סִיּוּר מֻדְרָךְ', 'סִיּוּר מוּדְרָךְ'],
  ['שִׁעוּרֵי בַּיִת', 'שִׁיעוּרֵי בַּיִת'],
  ['תַּלְמִיד מִצְטַיֵּן', 'תַּלְמִיד מִצְטַיֵּין'],
  ['חֹפֶשׁ הַגָּדוֹל', 'חוֹפֶשׁ הַגָּדוֹל'],
  ['חֹפֶשׁ', 'חוֹפֶשׁ'],
  ['לְטַיֵּל עִם הַכֶּלֶב', 'לְטַיֵּיל עִם הַכֶּלֶב'],
  ['קֹבֶץ מְצֹרָף', 'קוֹבֶץ מְצוֹרָף'],
  ['לִפְנִיּוֹת הַצִּבּוּר', 'לִפְנִיּוֹת הַצִּיבּוּר'],
  ['לַחֲזֹר בְּטֶלֶפוֹן', 'לַחֲזוֹר בְּטֶלֶפוֹן'],
  ['"hebrewPlain": "שיחה ממתינה"', '"hebrewPlain": "שיחה ממתנת"'],
  ['בִּטּוּחַ לְאֻמִּי', 'בִּיטּוּחַ לְאוּמִּי'],
  ['רִשָּׁיוֹן נְהִיגָה', 'רִישָּׁיוֹן נְהִיגָה'],
  ['רִשָּׁיוֹן', 'רִישָּׁיוֹן'],
  ['סִפּוּר חַיִּים', 'סִיפּוּר חַיִּים'],
  ['סִפּוּר', 'סִיפּוּר'],
  ['דִּבּוּר שׁוֹטֵף', 'דִּיבּוּר שׁוֹטֵף'],
  ['דִּבּוּר', 'דִּיבּוּר'],
  ['הֶשֵּׂגִים', 'הֶישֵּׂגִים'],
  ['הֶשֵּׂג', 'הֶישֵּׂג'],
  ['בִּטָּחוֹן', 'בִּיטָּחוֹן'],
  ['מוּזֵאוֹן', 'מוּזֵיאוֹן'],
  ['תֵּאַטְרוֹן', 'תֵּיאַטְרוֹן'],
  ['צִפּוֹרִים', 'צִיפּוֹרִים'],
  ['צִפּוֹר', 'צִיפּוֹר'],
  ['טְפָסִים', 'טְפָסִים'],
  ['טֹפֶס', 'טוֹפֶס'],
  ['בַּבֹּקֶר', 'בַּבּוֹקֶר'],
];

let totalReplaced = 0;
for (const [from, to] of replacements) {
  const matches = (content.match(new RegExp(from, 'g')) || []).length;
  if (matches > 0) {
    content = content.replaceAll(from, to);
    totalReplaced += matches;
    console.log(`Replaced "${from}" -> "${to}" (${matches} times)`);
  }
}

fs.writeFileSync(filePath, content, 'utf8');
console.log(`\nDone! Total replacements in ${filePath}: ${totalReplaced}`);
