/**
 * Получить пиктограмму для слова или фразы на иврите
 */
export function getHebrewPictogram(hebrewText: string): string | null {
  if (!hebrewText) return null;
  const clean = stripNikkud(hebrewText).trim();

  // 1. Точное совпадение
  if (HEBREW_PICTOGRAM_MAP[clean]) {
    return HEBREW_PICTOGRAM_MAP[clean];
  }

  // 2. Поиск по началу или ключевым словам
  for (const [key, icon] of Object.entries(HEBREW_PICTOGRAM_MAP)) {
    if (clean === key || clean.startsWith(`${key} `) || clean.endsWith(` ${key}`)) {
      return icon;
    }
  }

  // 3. Fallback по окончаниям (род и число)
  if (clean.endsWith('ות')) return '👥👩';
  if (clean.endsWith('ים')) return '👥👨';
  if (clean.endsWith('ה') || clean.endsWith('ת')) return '♀️';

  return null;
}

/**
 * Получить грамматический бейдж на иврите с пиктограммой
 */
export function getHebrewGenderLabel(gender: 'male' | 'female' | 'both' | string): {
  label: string;
  badgeClass: string;
  icon: string;
} {
  const g = gender.toLowerCase();
  if (g.includes('муж') || g.includes('male') || g.includes('זכר') || g === 'זָכָר') {
    return {
      label: 'זָכָר',
      badgeClass: 'bg-blue-50 dark:bg-blue-950/60 text-blue-700 dark:text-blue-300 border-blue-200 dark:border-blue-800',
      icon: '👨 ♂',
    };
  }
  if (g.includes('жен') || g.includes('female') || g.includes('נקבה') || g === 'נְקֵבָה') {
    return {
      label: 'נְקֵבָה',
      badgeClass: 'bg-rose-50 dark:bg-rose-950/60 text-rose-700 dark:text-rose-300 border-rose-200 dark:border-rose-800',
      icon: '👩 ♀',
    };
  }
  return {
    label: 'כְּלָלִי / מְשֻׁתָּף',
    badgeClass: 'bg-zinc-100 dark:bg-zinc-800 text-zinc-700 dark:text-zinc-300 border-zinc-200 dark:border-zinc-700',
    icon: '👥 ⚥',
  };
}
