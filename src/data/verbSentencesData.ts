/**
 * Получить группу предложений по инфинитиву или слову
 */
export function getVerbSentenceGroup(verbOrText: string): VerbSentenceGroup | null {
  if (!verbOrText) return null;
  const clean = stripNikkud(verbOrText.trim().toLowerCase());
  return VERB_SENTENCES_DATA[clean] || null;
}

/**
 * Получить список всех предложений для глагола
 */
export function getVerbDrillSentences(verbOrText: string): VerbDrillSentence[] {
  const group = getVerbSentenceGroup(verbOrText);
  return group ? group.sentences : [];
}

/**
 * Получить предложение конкретного времени
 */
export function getVerbSentenceByTense(
  verbOrText: string,
  tense: VerbTense = 'present'
): VerbDrillSentence | null {
  const sentences = getVerbDrillSentences(verbOrText);
  return sentences.find((s) => s.tense === tense) || sentences[0] || null;
}
