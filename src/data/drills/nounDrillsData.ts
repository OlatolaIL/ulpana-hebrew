/**
 * Получить обучающий объект для существительного по словарной форме (с огласовками или без).
 */
export function getNounDrill(rawWord: string): NounDrillItem | null {
  if (!rawWord) return null;
  const plain = stripNikkud(rawWord).trim();
  if (NOUN_DRILLS_DATA[plain]) {
    return NOUN_DRILLS_DATA[plain];
  }
  // Поиск по точному совпадению
  if (NOUN_DRILLS_DATA[rawWord]) {
    return NOUN_DRILLS_DATA[rawWord];
  }
  return null;
}
