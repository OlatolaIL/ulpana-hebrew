/**
 * Получить или динамически сгенерировать телефонный сценарий для любого урока (1-100)
 */
export function getLessonPhoneScenario(lesson: Lesson, gender: UserGender): PhoneScenario {
  const isFemale = gender === 'female';

  // 1. Проверяем кастомный сценарий внутри самого объекта урока
  if (lesson.phoneScenario) {
    return adaptGenderInScenario(lesson.phoneScenario, isFemale, lesson.number);
  }

  // 2. Проверяем словарь готовых сценариев
  if (BESPOKE_PHONE_SCENARIOS[lesson.number]) {
    return adaptGenderInScenario(BESPOKE_PHONE_SCENARIOS[lesson.number], isFemale, lesson.number);
  }

  // 3. Системный автоматический генератор для ВСЕХ остальных уроков (1-100)
  const dial = lesson.dialogue;
  const aiRole = dial.aiRole || 'Собеседник';
  const userRole = dial.userRole || 'Собеседник';
  const aiRoleLower = aiRole.toLowerCase();
  const situationLower = (dial.situation || '').toLowerCase();
  const titleLower = (lesson.titleRussian || '').toLowerCase();
  const catLower = (lesson.category || '').toLowerCase();

  // Определяем тип звонка: явный из данных урока → иначе ключевые слова как запасной вариант
  const explicitCallType = lesson.dialogue.callType;
  const isIncoming = explicitCallType
    ? explicitCallType === 'incoming'
    : (aiRoleLower.includes('נהג') ||
      aiRoleLower.includes('שליח') ||
      aiRoleLower.includes('חבר') ||
      aiRoleLower.includes('שכן') ||
      aiRoleLower.includes('водитель') ||
      aiRoleLower.includes('курьер') ||
      aiRoleLower.includes('сосед') ||
      aiRoleLower.includes('соседк') ||
      aiRoleLower.includes('друг') ||
      aiRoleLower.includes('подруг') ||
      aiRoleLower.includes('знаком') ||
      aiRoleLower.includes('коллег') ||
      aiRoleLower.includes('одногрупп') ||
      aiRoleLower.includes('однокурс') ||
      aiRoleLower.includes('приятел') ||
      aiRoleLower.includes('мама') ||
      aiRoleLower.includes('папа') ||
      aiRoleLower.includes('брат') ||
      aiRoleLower.includes('сестр') ||
      aiRoleLower.includes('сын') ||
      aiRoleLower.includes('дочь') ||
      aiRoleLower.includes('родствен') ||
      situationLower.includes('вам звонит') ||
      situationLower.includes('звонит вам'));


  const callType: PhoneCallType = isIncoming ? 'incoming' : 'outgoing';

  const cleanTopic = cleanGrammarJargon(dial.title || lesson.category || 'Повседневное общение');
  const rawSituation = dial.situation || '';
  const cleanSituationDesc = cleanGrammarJargon(
    rawSituation
      .replace(/К вам подходит /gi, 'С вами говорит ')
      .replace(/Вы пришли в /gi, 'Вы звоните в ')
      .replace(/Вы пришли на /gi, 'Вы звоните на ')
      .replace(/Вы стоите на /gi, 'Вы звоните на ')
      .replace(/Вы сидите за столиком в /gi, 'Вы звоните в ')
  );

  const situationSummary = isIncoming
    ? `Вам звонит ${aiRole}. ${cleanSituationDesc || cleanTopic}`
    : `Вы звоните (${aiRole}). ${cleanSituationDesc || cleanTopic}`;

  const callerObjective = isIncoming
    ? `Кратко обсудить с учеником бытовой вопрос («${cleanTopic}») в роли «${aiRole}» и тепло завершить звонок.`
    : `Принять звонок в роли «${aiRole}», помочь ученику («${userRole}») по вопросу «${cleanTopic}» и вежливо завершить разговор.`;

  const studentObjective = isIncoming
    ? `Ответить на вопрос собеседника и завершить звонок.`
    : `Поздороваться, изложить свой запрос («${cleanTopic}») и договориться.`;

  let initialGreetingHeb = '';
  let initialGreetingTr = '';
  let initialGreetingRu = '';

  const initHeb = dial.initialMessage?.hebrew || '';
  const isVisualInPerson =
    initHeb.includes('תְּמוּנָה') ||
    initHeb.includes('תמונה') ||
    initHeb.includes('מִסְתַּכֵּל') ||
    initHeb.includes('רוֹאֶה') ||
    initHeb.includes('תִּסְתַּכֵּל');

  // Если в уроке есть авторское начальное сообщение — бережно используем его!
  if (initHeb && !isVisualInPerson) {
    let heb = dial.initialMessage!.hebrew.trim();
    let tr = dial.initialMessage!.transcription ? dial.initialMessage!.transcription.trim() : '';
    let ru = dial.initialMessage!.translation ? dial.initialMessage!.translation.trim() : '';

    // Для входящего звонка, если ещё нет "הלו", добавим телефонное приветствие
    if (isIncoming && !heb.startsWith('הַלּוֹ') && !heb.startsWith('הלו')) {
      heb = `הַלּוֹ? ${heb}`;
      tr = tr ? `hалó? ${tr}` : tr;
      ru = ru ? `Алло? ${ru}` : ru;
    }

    initialGreetingHeb = heb;
    initialGreetingTr = tr;
    initialGreetingRu = ru;
  } else {
    initialGreetingHeb = isIncoming ? 'הַלּוֹ? שָׁלוֹם! מָה נִשְׁמַע?' : 'שָׁלוֹם! כֵּן, אֵיךְ אֶפְשָׁר לַעֲזֹר?';
    initialGreetingTr = isIncoming ? 'hалó? шалóм! ма нишмá?' : 'шалóм! кен, эйх эфшáр лаазóр?';
    initialGreetingRu = isIncoming ? 'Алло? Привет! Как дела?' : 'Здравствуйте! Да, чем могу помочь?';
  }

  // Адаптация рода в приветствии
  if (isFemale) {
    initialGreetingHeb = initialGreetingHeb
      .replace(/לְךָ/g, 'לָךְ')
      .replace(/שֶׁלְּךָ/g, 'שֶׁלָּךְ')
      .replace(/שֶׁלְךָ/g, 'שֶׁלָּךְ')
      .replace(/תִּרְצֶה/g, 'תִּרְצִי')
      .replace(/מְחַפֵּשׂ/g, 'מְחַפֶּשֶׂת')
      .replace(/רוֹצֶה/g, 'רוֹצָה')
      .replace(/צָרִיךְ/g, 'צְרִיכָה')
      .replace(/יָכוֹל/g, 'יְכוֹלָה')
      .replace(/אַתָּה/g, 'אַתְּ');
    initialGreetingTr = initialGreetingTr
      .replace(/лэхá/g, 'лах')
      .replace(/шельхá/g, 'шелáх')
      .replace(/тирцé/g, 'тирцӣ')
      .replace(/мэхапэ́с/g, 'мэхапэ́сэт')
      .replace(/роцé/g, 'роцá')
      .replace(/царӣх/g, 'црихá')
      .replace(/атá/g, 'ат');
  }

  const dynamicUsefulWords: PhoneScenarioWord[] = (lesson.vocabulary || []).slice(0, 7).map((w) => ({
    hebrew: w.hebrew,
    transcription: w.transcription || '',
    translation: w.translation,
  }));

  if (!dynamicUsefulWords.some((w) => w.hebrew.includes('הַלּוֹ') || w.hebrew.includes('שָׁלוֹם'))) {
    dynamicUsefulWords.unshift({
      hebrew: 'הַלּוֹ, שָׁלוֹם!',
      transcription: 'hалó, шалóм!',
      translation: 'алло, привет / здравствуйте',
    });
  }
  if (!dynamicUsefulWords.some((w) => w.hebrew.includes('לְהִתְרָאוֹת'))) {
    dynamicUsefulWords.push({
      hebrew: 'לְהִתְרָאוֹת',
      transcription: 'лэhитраóт',
      translation: 'до свидания / пока',
    });
  }

  const firstVocabWord = lesson.vocabulary?.[0]?.hebrew || '';
  const isFemaleRole = /שרה|גלית|מרים|רחל|דנה|מיכל|רונית|אורית|יעל|хозяйка|секретарь|продавщица|официантка|подруга/i.test(aiRole);
  const scenarioCallerGender: 'male' | 'female' = isFemaleRole ? 'female' : 'male';

  return {
    callType,
    callerName: aiRole,
    callerNameRu: aiRole,
    callerRole: aiRole,
    callerGender: scenarioCallerGender,
    userRole: userRole,
    avatarEmoji: getEmojiForCategory(lesson.category),
    situationSummary,
    callerObjective,
    studentObjective,
    completionCondition: isIncoming
      ? 'Ученик ответил на вопрос собеседника и согласовал детали.'
      : 'Ученик высказал свою просьбу и получил подтверждение.',
    targetTurns: 3,
    initialGreeting: {
      hebrew: initialGreetingHeb,
      transcription: initialGreetingTr,
      translation: initialGreetingRu,
    },
    goals: dial.goals && dial.goals.length > 0
      ? dial.goals
      : [
          'Ответить на звонок и поддержать беседу',
          'Использовать ключевые слова из урока',
          'Вежливо завершить разговор (לְהִתְרָאוֹת)',
        ],
    suggestedReplies: [
      {
        hebrew: isIncoming
          ? (isFemale ? 'שָׁלוֹם! הַכֹּל בְּסֵדֶר, מָה אִתָּךְ?' : 'שָׁלוֹם! הַכֹּל בְּסֵדֶר, מָה אִתְּךָ?')
          : (firstVocabWord
              ? (isFemale ? `שָׁלוֹם, אֲנִי רוֹצָה ${firstVocabWord}, בְּבַקָּשָׁה.` : `שָׁלוֹם, אֲנִי רוֹצֶה ${firstVocabWord}, בְּבַקָּשָׁה.`)
              : 'שָׁלוֹם, אֶפְשָׁר עֶזְרָה בְּבַקָּשָׁה?'),
        transcription: isIncoming
          ? (isFemale ? 'шалóм! hакóль бэсэ́дер, ма итáх?' : 'шалóм! hакóль бэсэ́дер, ма итхá?')
          : (firstVocabWord
              ? (isFemale ? 'шалóм, анӣ роцá ..., бэвакашá.' : 'шалóм, анӣ роцé ..., бэвакашá.')
              : 'шалóм, эфшáр эзрá бэвакашá?'),
        translation: isIncoming
          ? 'Привет! Все хорошо, как ты?'
          : (firstVocabWord
              ? (isFemale ? 'Здравствуйте, я хочу ... (ж.р.), пожалуйста.' : 'Здравствуйте, я хочу ... (м.р.), пожалуйста.')
              : 'Здравствуйте, можно помощь пожалуйста?'),
      },
      {
        hebrew: 'תּוֹדָה רַבָּה, יוֹם טוֹב וּלְהִתְרָאוֹת!',
        transcription: 'тодá рабá, йом тов у-лэhитраóт!',
        translation: 'Большое спасибо, хорошего дня и до свидания!',
      },
    ],
    vocabularyHints: dial.vocabularyHints || (lesson.vocabulary || []).slice(0, 5).map((w) => w.hebrew),
    usefulWords: dynamicUsefulWords,
    systemPromptAddition: `ТВОЙ ПЕРСОНАЖ (ИИ): ${aiRole}.
РОЛЬ УЧЕНИКА: ${userRole}.
СИТУАЦИЯ: ${rawSituation || cleanTopic}.
${isIncoming
  ? `ТЫ ЗВОНИШЬ УЧЕНИКУ — ты инициируешь разговор от лица «${aiRole}».`
  : `УЧЕНИК ОБРАЩАЕТСЯ К ТЕБЕ — ты принимаешь обращение в образе «${aiRole}» и помогаешь ему («${userRole}»).`}
ТЫ — ЖИВОЙ ЧЕЛОВЕК, А НЕ ПРЕПОДАВАТЕЛЬ И НЕ БОТ!
КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО:
- Путать роли: ты — ${aiRole}, а ученик — ${userRole}! Никогда не говори от лица ученика!
- Задавать экзаменационные вопросы, спрашивать перевод («Как сказать...?», «איך אומרים...?») или проверять грамматику.
- Прощаться и вешать трубку раньше 3-го раунда.
ПРАВИЛА ВЕДЕНИЯ ДИАЛОГА (3 раунда):
- ВАЖНЕЙШЕЕ ПРАВИЛО: Внимательно слушай ученика! Если ученик УЖЕ назвал какую-то деталь ситуации или ответил на часть вопроса (например: сахар, размер, имя, адрес, время, цену, товар/услугу), КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО переспрашивать её! Засчитай этот пункт и задай вопрос ТОЛЬКО о тех деталях, которые ещё не были названы!
- Раунды 1-2: Тепло и коротко отреагируй на слова ученика, затем задай следующий логичный наводящий вопрос по ситуации от лица «${aiRole}». НЕ ВЕШАЙ ТРУБКУ!
- Раунд 3 (финал): Подтверди, поблагодари или пожелай хорошего дня, установи isCompleted: true и shouldHangUp: true.`,

  };
}

function adaptGenderInScenario(
  scenario: PhoneScenario,
  isFemale: boolean,
  lessonNumber?: number
): PhoneScenario {
  const copy: PhoneScenario = JSON.parse(JSON.stringify(scenario));
  if (isFemale) {
    copy.initialGreeting.hebrew = copy.initialGreeting.hebrew
      .replace(/לְךָ/g, 'לָךְ')
      .replace(/שֶׁלְּךָ/g, 'שֶׁלָּךְ')
      .replace(/שֶׁלְךָ/g, 'שֶׁלָּךְ')
      .replace(/תִּרְצֶה/g, 'תִּרְצִי')
      .replace(/מְחַפֵּשׂ/g, 'מְחַפֶּשֶׂת')
      .replace(/רוֹצֶה/g, 'רוֹצָה')
      .replace(/צָרִיךְ/g, 'צְרִיכָה')
      .replace(/יָכוֹל/g, 'יְכוֹלָה')
      .replace(/אַתָּה/g, 'אַתְּ')
      .replace(/שֶׁשָּׁלַחְתָּ/g, 'שֶׁשָּׁלַחַתְּ')
      .replace(/שָׁלַחְתָּ/g, 'שָׁלַחַתְּ');
    copy.initialGreeting.transcription = copy.initialGreeting.transcription
      .replace(/лэхá/g, 'лах')
      .replace(/шельхá/g, 'шелáх')
      .replace(/тирцé/g, 'тирцӣ')
      .replace(/мэхапэ́с/g, 'мэхапэ́сэт')
      .replace(/роцé/g, 'роцá')
      .replace(/царӣх/g, 'црихá')
      .replace(/атá/g, 'ат')
      .replace(/ше-шалáхта/g, 'ше-шалáхат')
      .replace(/шалáхта/g, 'шалáхат');
    if (copy.initialGreeting.translation) {
      copy.initialGreeting.translation = copy.initialGreeting.translation
        .replace(/ты прислал/g, 'ты прислала');
    }

    if (copy.suggestedReplies) {
      copy.suggestedReplies = copy.suggestedReplies.map((reply) => ({
        ...reply,
        hebrew: reply.hebrew.replace(/אֲנִי רוֹצֶה/g, 'אֲנִי רוֹצָה'),
        transcription: reply.transcription ? reply.transcription.replace(/анӣ роцé/g, 'анӣ роцá') : reply.transcription,
        translation: reply.translation ? reply.translation.replace(/\(м\.р\.\)/g, '(ж.р.)') : reply.translation,
      }));
    }

    if (lessonNumber === 1) {
      if (copy.suggestedReplies?.[1]) {
        copy.suggestedReplies[1].hebrew = copy.suggestedReplies[1].hebrew.replace('דָּוִד', 'שָׂרָה');
        copy.suggestedReplies[1].transcription = copy.suggestedReplies[1].transcription.replace('Давӣд', 'Сáра');
        copy.suggestedReplies[1].translation = copy.suggestedReplies[1].translation.replace('Давид', 'Сара');
      }
      if (copy.completionCondition) {
        copy.completionCondition = copy.completionCondition
          .replace('Ученик ответил на приветствие и назвал', 'Ученица ответила на приветствие и назвала')
          .replace('Ученик', 'Ученица');
      }
      if (copy.userRole) {
        copy.userRole = copy.userRole.replace('Ученик', 'Ученица');
      }
      if (copy.goals) {
        copy.goals = copy.goals.map((g) => g.replace('אֲנִי גָּר בְּדִירָה', 'אֲנִי גָּרָה בְּדִירָה'));
      }
    } else if (lessonNumber === 2) {
      if (copy.suggestedReplies?.[0]) {
        copy.suggestedReplies[0].hebrew = copy.suggestedReplies[0].hebrew.replace('אֲנִי רוֹצֶה', 'אֲנִי רוֹצָה');
        copy.suggestedReplies[0].transcription = copy.suggestedReplies[0].transcription.replace('анӣ роцé', 'анӣ роцá');
      }
      if (copy.initialGreeting) {
        copy.initialGreeting = {
          ...copy.initialGreeting,
          hebrew: copy.initialGreeting.hebrew.replace('מָה אַתָּה רוֹצֶה', 'מָה אַתְּ רוֹצָה'),
          transcription: copy.initialGreeting.transcription.replace('ма атá роцé', 'ма ат роцá'),
        };
      }
      if (copy.completionCondition) {
        copy.completionCondition = copy.completionCondition.replace(
          'Ученик сделал заказ кофе и узнал',
          'Ученица сделала заказ кофе и узнала'
        );
      }
    } else if (lessonNumber === 3) {
      if (copy.studentObjective) {
        copy.studentObjective = copy.studentObjective.replace('אֲנִי גָּר בְּ...', 'אֲנִי גָּרָה בְּ...');
      }
      if (copy.completionCondition) {
        copy.completionCondition = copy.completionCondition.replace('Ученик назвал', 'Ученица назвала');
      }
      if (copy.goals) {
        copy.goals = copy.goals.map((g) => g.replace('אֲנִי גָּר בְּתֵל אָבִיב', 'אֲנִי גָּרָה בְּתֵל אָבִיב'));
      }
      if (copy.suggestedReplies?.[1]) {
        copy.suggestedReplies[1].hebrew = copy.suggestedReplies[1].hebrew.replace('אֲנִי גָּר בְּתֵל אָבִיב', 'אֲנִי גָּרָה בְּתֵל אָבִיב');
        copy.suggestedReplies[1].transcription = copy.suggestedReplies[1].transcription.replace('анӣ гар бэ-Тэль Авӣв', 'анӣ гарá бэ-Тэль Авӣв');
      }
    } else if (lessonNumber === 4) {
      if (copy.completionCondition) {
        copy.completionCondition = copy.completionCondition.replace('Ученик назвал', 'Ученица назвала');
      }
      if (copy.suggestedReplies?.[1]) {
        copy.suggestedReplies[1].hebrew = copy.suggestedReplies[1].hebrew.replace('אֲנִי גָּר בְּתֵל אָבִיב', 'אֲנִי גָּרָה בְּתֵל אָבִיב');
        copy.suggestedReplies[1].transcription = copy.suggestedReplies[1].transcription.replace('анӣ гар бэ-Тэль Авӣв', 'анӣ гарá бэ-Тэль Авӣв');
      }
      if (copy.suggestedReplies?.[2]) {
        copy.suggestedReplies[2].hebrew = copy.suggestedReplies[2].hebrew.replace('אֲנִי מְדַבֵּר רוּסִית', 'אֲנִי מְדַבֶּרֶת רוּסִית');
        copy.suggestedReplies[2].transcription = copy.suggestedReplies[2].transcription.replace('анӣ мэдабэ́р русӣт', 'анӣ мэдабэ́рэт русӣт');
      }
    } else if (lessonNumber === 5) {
      if (copy.userRole) {
        copy.userRole = 'Покупательница';
      }
      if (copy.studentObjective) {
        copy.studentObjective = copy.studentObjective.replace('«אֲנִי רוֹצֶה לֶחֶם וּגְבִינָה»', '«אֲנִי רוֹצָה לֶחֶם וּגְבִינָה»');
      }
      if (copy.completionCondition) {
        copy.completionCondition =
          'Покупательница назвала нужные продукты («רוצה לחם/גבינה/עגבניות»), уточнила количество или спросила цену («כמה זה עולה»).';
      }
      if (copy.goals) {
        copy.goals = copy.goals.map((g) => g.replace('אֲנִי רוֹצֶה', 'אֲנִי רוֹצָה'));
      }
      if (copy.vocabularyHints) {
        copy.vocabularyHints = copy.vocabularyHints.map((vh) => vh.replace('אֲנִי רוֹצֶה', 'אֲנִי רוֹצָה'));
      }
      if (copy.suggestedReplies?.[0]) {
        copy.suggestedReplies[0].hebrew = copy.suggestedReplies[0].hebrew.replace('אֲנִי רוֹצֶה', 'אֲנִי רוֹצָה');
        copy.suggestedReplies[0].transcription = copy.suggestedReplies[0].transcription.replace('анӣ роцé', 'анӣ роцá');
      }
      if (copy.usefulWords) {
        copy.usefulWords = copy.usefulWords.map((word) => {
          if (word.hebrew === 'אֲנִי רוֹצֶה') {
            return {
              ...word,
              hebrew: 'אֲנִי רוֹצָה',
              transcription: 'анӣ роцá',
              translation: 'я хочу (ж.р.)',
            };
          }
          return word;
        });
      }
    } else if (lessonNumber === 7) {
      if (copy.completionCondition) {
        copy.completionCondition = copy.completionCondition.replace('Ученик согласовал', 'Ученица согласовала');
      }
    }
  }
  return copy;
}

function getEmojiForCategory(category: string): string {
  const cat = (category || '').toLowerCase();
  if (cat.includes('кафе') || cat.includes('еда')) return '☕';
  if (cat.includes('дом') || cat.includes('квартира')) return '🏠';
  if (cat.includes('город') || cat.includes('такси') || cat.includes('дорога')) return '🚕';
  if (cat.includes('здоровье') || cat.includes('врач')) return '🏥';
  if (cat.includes('работа') || cat.includes('офис')) return '💼';
  if (cat.includes('покуп') || cat.includes('магазин')) return '🛒';
  return '📞';
}
