/**
 * Получение задания сочинения для любого урока (1 - 100)
 */
export function getLessonEssayPrompt(lessonId: number): LessonEssayPrompt {
  if (BESPOKE_ESSAY_PROMPTS[lessonId]) {
    return BESPOKE_ESSAY_PROMPTS[lessonId];
  }

  const lesson = getLessonById(lessonId);
  const targetWords = (lesson.vocabulary || []).slice(0, 6).map((w) => ({
    hebrew: w.hebrew,
    translation: w.translation,
    transcription: w.transcription,
  }));

  const isBet = lesson.level === 'bet' || lessonId > 50;
  const minWords = lessonId <= 10 ? 10 : lessonId <= 30 ? 15 : isBet ? 30 : 20;

  return {
    topicRu: `Рассказ по теме: ${lesson.titleRussian}`,
    topicHe: lesson.titleHebrew,
    situationRu: `Составьте связный авторский рассказ (из 3–6 предложений) по теме «${lesson.titleRussian}». Опишите ситуацию от своего лица, используя пройденную лексику и грамматику урока.`,
    grammarFocusRu:
      'Внимание на порядок слов: в иврите признак (прилагательное) всегда следует ПОСЛЕ предмета, а частица отрицания — строго ПЕРЕД действием (глаголом). Следите за согласованием рода подлежащего и сказуемого.',
    minWords,
    suggestedWords: targetWords,
    sampleEssay: {
      hebrew: `שָׁלוֹם, זֶה סִפּוּר עַל ${lesson.titleHebrew}. אֲנִי לוֹמֵד עִבְרִית בָּאוּלְפָּן וְזֶה נוֹשֵׂא חָשׁוּב מְאוֹד.`,
      transcription: `шалóм, зэ сипӯр аль ${lesson.titleRussian}. анӣ ломэ́д иврӣт ба-ульпáн вэ-зэ носэ́ хашӯв мэóд.`,
      translation: `Здравствуйте, это рассказ на тему «${lesson.titleRussian}». Я учу иврит в ульпане, и это очень важная тема.`,
    },
  };
}